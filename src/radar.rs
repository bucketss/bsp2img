use std::path::Path;

use anyhow::{Context, Result, bail};

use crate::kv1::{self, Block, Value};
use crate::overview::Radar;
use crate::render::Cuts;
use crate::scene::num;

pub const OPEN: f64 = 16384.0;
pub const DEFAULT: &str = "default";

#[derive(Clone, Debug, PartialEq)]
pub struct Section {
    pub name: String,
    pub alt_min: f64,
    pub alt_max: f64,
    pub frame: Option<Radar>,
}

impl Section {
    pub fn all() -> Section {
        Section { name: DEFAULT.into(), alt_min: -OPEN, alt_max: OPEN, frame: None }
    }

    pub fn is_default(&self) -> bool {
        self.name.eq_ignore_ascii_case(DEFAULT)
    }

    pub fn cuts(&self, c: &Cuts) -> Cuts {
        Cuts { zmin: c.zmin.max(self.alt_min), zmax: c.zmax.min(self.alt_max), ..*c }
    }

    pub fn contains(&self, z: f64) -> bool {
        z >= self.alt_min && z < self.alt_max
    }

    pub fn range(&self) -> String {
        format!("z {} .. {}", num(self.alt_min), num(self.alt_max))
    }
}

pub fn stem(map: &str, section: &str) -> String {
    if section.is_empty() || section.eq_ignore_ascii_case(DEFAULT) { map.to_string() } else { format!("{map}_{section}") }
}

#[derive(Clone, Debug, PartialEq)]
pub struct Official {
    pub name: String,
    pub frame: Radar,
    pub rotate: f64,
    pub zoom: f64,
    pub insets: Option<[f64; 4]>,
    pub sections: Vec<Section>,
    pub icons: Vec<(String, [f64; 2])>,
    pub material: Option<String>,
    pub autogen: bool,
}

fn frame(b: &Block) -> Option<Radar> {
    Some(Radar { pos_x: kv1::num(b, "pos_x")?, pos_y: kv1::num(b, "pos_y")?, scale: kv1::num(b, "scale")? })
}

impl Official {
    pub fn new(name: &str, frame: Radar) -> Official {
        Official {
            name: name.to_string(),
            frame,
            rotate: 0.0,
            zoom: 1.0,
            insets: None,
            sections: vec![Section::all()],
            icons: Vec::new(),
            material: None,
            autogen: false,
        }
    }

    pub fn parse(top: &Block) -> Result<Official> {
        let (name, b) = match top.iter().find_map(|(k, v)| v.block().map(|b| (k.clone(), b))) {
            Some((k, b)) if kv1::get(top, "pos_x").is_none() => (k, b),
            _ => (String::new(), top),
        };
        let Some(fr) = frame(b) else {
            let miss: Vec<&str> = ["pos_x", "pos_y", "scale"].into_iter().filter(|k| kv1::num(b, k).is_none()).collect();
            bail!("{} missing or not a number", miss.join(", "));
        };
        if fr.scale <= 0.0 || !fr.scale.is_finite() {
            bail!("scale {} is not positive", fr.scale);
        }
        let insets = ["inset_left", "inset_top", "inset_right", "inset_bottom"].map(|k| kv1::num(b, k));
        let insets = insets.iter().all(Option::is_some).then(|| insets.map(|v| v.unwrap_or(0.0)));
        let mut sections = Vec::new();
        for (n, v) in kv1::get(b, "verticalsections").and_then(Value::block).into_iter().flatten() {
            let Some(s) = v.block() else { continue };
            let alt_min = kv1::num(s, "AltitudeMin").unwrap_or(-OPEN);
            let alt_max = kv1::num(s, "AltitudeMax").unwrap_or(OPEN);
            sections.push(Section { name: n.clone(), alt_min, alt_max, frame: None });
        }
        if sections.is_empty() {
            sections.push(Section::all());
        }
        for (n, v) in kv1::get(b, "Volumes").and_then(Value::block).into_iter().flatten() {
            if let Some(f) = v.block().and_then(frame) {
                sections.push(Section { name: n.clone(), alt_min: -OPEN, alt_max: OPEN, frame: Some(f) });
            }
        }
        let mut icons = Vec::new();
        for (k, v) in b {
            let Some(base) = k.strip_suffix("_x").or_else(|| k.strip_suffix("_X")) else { continue };
            if base.eq_ignore_ascii_case("pos") {
                continue;
            }
            if let (Some(x), Some(y)) = (v.num(), kv1::num(b, &format!("{base}_y"))) {
                icons.push((base.to_string(), [x, y]));
            }
        }
        Ok(Official {
            name,
            frame: fr,
            rotate: kv1::num(b, "rotate").unwrap_or(0.0),
            zoom: kv1::num(b, "zoom").unwrap_or(1.0),
            insets,
            sections,
            icons,
            material: kv1::get(b, "material").and_then(Value::str).map(str::to_string),
            autogen: kv1::num(b, "autogenerated_tga").is_some_and(|v| v != 0.0),
        })
    }

    pub fn parse_bytes(b: &[u8]) -> Result<Official> {
        Official::parse(&kv1::parse_bytes(b)?)
    }

    pub fn read(path: &Path) -> Result<Official> {
        let b = std::fs::read(path).with_context(|| format!("reading {}", path.display()))?;
        Official::parse_bytes(&b).with_context(|| format!("parsing {}", path.display()))
    }

    pub fn levels(&self) -> impl Iterator<Item = &Section> {
        self.sections.iter().filter(|s| s.frame.is_none())
    }

    pub fn volumes(&self) -> impl Iterator<Item = &Section> {
        self.sections.iter().filter(|s| s.frame.is_some())
    }

    pub fn section(&self, name: &str) -> Option<&Section> {
        self.sections.iter().find(|s| s.name.eq_ignore_ascii_case(name))
    }

    pub fn section_for(&self, z: f64) -> Option<&Section> {
        self.levels().find(|s| s.contains(z))
    }

    pub fn frame_of(&self, s: &Section) -> Radar {
        s.frame.unwrap_or(self.frame)
    }

    pub fn icon(&self, name: &str) -> Option<[f64; 2]> {
        self.icons.iter().find(|(n, _)| n.eq_ignore_ascii_case(name)).map(|(_, p)| *p)
    }

    pub fn icon_world(&self, name: &str) -> Option<(f64, f64)> {
        self.icon(name).map(|[u, v]| self.frame.from_norm(u, v))
    }

    pub fn txt(&self) -> String {
        let name = &self.name;
        let mut l = vec![format!("// overview description file for {name}"), String::new(), format!("\"{name}\""), "{".into()];
        let q = |k: &str, v: String| format!("\t\"{k}\"{}\"{v}\"", if k.len() < 6 { "\t\t" } else { "\t" });
        l.push(q("material", self.material.clone().unwrap_or_else(|| format!("overviews/{name}"))));
        if self.autogen {
            l.push(q("autogenerated_tga", "1".into()));
        }
        l.push(q("pos_x", num(self.frame.pos_x)));
        l.push(q("pos_y", num(self.frame.pos_y)));
        l.push(q("scale", num(self.frame.scale)));
        l.push(q("rotate", num(self.rotate)));
        l.push(q("zoom", num(self.zoom)));
        if let Some(i) = self.insets {
            for (k, v) in ["inset_left", "inset_top", "inset_right", "inset_bottom"].iter().zip(i) {
                l.push(q(k, num(v)));
            }
        }
        let levels: Vec<&Section> = self.levels().collect();
        if levels.len() > 1 {
            l.extend([String::new(), "\t\"verticalsections\"".into(), "\t{".into()]);
            for s in levels {
                l.extend([format!("\t\t\"{}\"", s.name), "\t\t{".into()]);
                l.push(format!("\t\t\t\"AltitudeMax\"\t\"{}\"", num(s.alt_max)));
                l.push(format!("\t\t\t\"AltitudeMin\"\t\"{}\"", num(s.alt_min)));
                l.push("\t\t}".into());
            }
            l.push("\t}".into());
        }
        let vols: Vec<&Section> = self.volumes().collect();
        if !vols.is_empty() {
            l.extend([String::new(), "\t\"Volumes\"".into(), "\t{".into()]);
            for s in vols {
                let f = self.frame_of(s);
                l.extend([format!("\t\t\"{}\"", s.name), "\t\t{".into()]);
                l.push(format!("\t\t\t\"pos_x\"\t\t\"{}\"", num(f.pos_x)));
                l.push(format!("\t\t\t\"pos_y\"\t\t\"{}\"", num(f.pos_y)));
                l.push(format!("\t\t\t\"scale\"\t\t\"{}\"", num(f.scale)));
                l.push("\t\t}".into());
            }
            l.push("\t}".into());
        }
        if !self.icons.is_empty() {
            l.push(String::new());
            for (n, [x, y]) in &self.icons {
                l.push(q(&format!("{n}_x"), format!("{x:.3}")));
                l.push(q(&format!("{n}_y"), format!("{y:.3}")));
            }
        }
        l.push("}".into());
        l.iter().map(|s| format!("{s}\r\n")).collect()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn nuke_sections_and_icons() {
        let t = "\"de_nuke\"\n{\n\"material\" \"overviews/de_nuke\" // x\n\"pos_x\" \"-3453\"\n\"pos_y\" \"2887\"\n\"scale\" \"7\"\n\"verticalsections\"\n{\n\"default\" // p\n{\n\"AltitudeMax\" \"10000\"\n\"AltitudeMin\" \"-495\"\n}\n\"lower\"\n{\n\"AltitudeMax\" \"-495\"\n\"AltitudeMin\" \"-10000\"\n}\n}\n\"CTSpawn_x\" \"0.82\"\n\"CTSpawn_y\" \"0.45\"\n\"bombA_x\" \"0.58\"\n\"bombA_y\" \"0.48\"\n}";
        let o = Official::parse(&kv1::parse(t).unwrap()).unwrap();
        assert_eq!(o.name, "de_nuke");
        assert_eq!(o.frame, Radar { pos_x: -3453.0, pos_y: 2887.0, scale: 7.0 });
        assert_eq!(o.sections.len(), 2);
        assert_eq!(o.section_for(-600.0).unwrap().name, "lower");
        assert_eq!(o.section_for(-495.0).unwrap().name, "default");
        assert_eq!(o.icons.len(), 2);
        let (x, y) = o.icon_world("ctspawn").unwrap();
        assert!((x - (-3453.0 + 0.82 * 7168.0)).abs() < 1e-6 && (y - (2887.0 - 0.45 * 7168.0)).abs() < 1e-6);
        let back = Official::parse_bytes(o.txt().as_bytes()).unwrap();
        assert_eq!(back.sections, o.sections);
        assert_eq!(back.frame, o.frame);
        assert_eq!(stem("de_nuke", "lower"), "de_nuke_lower");
        assert_eq!(stem("de_nuke", "Default"), "de_nuke");
    }

    #[test]
    fn volumes_and_missing() {
        let t = "\"r\" { \"Volumes\" { \"room1\" { \"pos_x\" \"1\" \"pos_y\" \"2\" \"scale\" \"3\" } } \"pos_x\" \"-5\" \"pos_y\" \"5\" \"scale\" \"10\" }";
        let o = Official::parse(&kv1::parse(t).unwrap()).unwrap();
        assert_eq!(o.levels().count(), 1);
        assert_eq!(o.volumes().next().unwrap().frame.unwrap().scale, 3.0);
        assert!(Official::parse(&kv1::parse("\"r\" { \"pos_x\" \"1\" }").unwrap()).is_err());
    }
}
